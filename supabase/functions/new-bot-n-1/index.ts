type Msg = { role: string; content: string };

async function askModel(messages: Msg[]): Promise<string> {
  const res = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${OPENAI_KEY}`,
    },
    body: JSON.stringify({
      model: MODEL,
      max_completion_tokens: 1500,
      messages: [{ role: "system", content: SYSTEM_PROMPT }, ...messages],
    }),
  });
  if (!res.ok) throw new Error(`openai failed: ${res.status} ${await res.text()}`);
  const data = await res.json();
  return (data?.choices?.[0]?.message?.content ?? "").trim();
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  if (req.method !== "POST") return reply({ error: "method not allowed" }, 405);

  let body: { messages?: unknown };
  try {
    body = await req.json();
  } catch {
    return reply({ error: "invalid json" }, 400);
  }

  const raw = body?.messages;
  if (!Array.isArray(raw) || raw.length === 0) {
    return reply({ error: "messages must be a non-empty array" }, 400);
  }
  if (raw.length > MAX_TURNS) {
    return reply({ error: "too many turns" }, 400);
  }

  const messages: Msg[] = [];
  for (const m of raw) {
    const role = (m as Msg)?.role;
    const content = (m as Msg)?.content;
    if (role !== "user" && role !== "assistant") {
      return reply({ error: "role must be 'user' or 'assistant'" }, 400);
    }
    if (typeof content !== "string" || content.trim() === "") {
      return reply({ error: "content must be a non-empty string" }, 400);
    }
    if (content.length > MAX_CHARS) {
      return reply({ error: "content too long" }, 400);
    }
    messages.push({ role, content });
  }

  try {
    const text = await askModel(messages);
    return reply({ reply: text });
  } catch (err) {
    console.error("new-bot-n-1 failed:", err);
    return reply({ error: "model call failed" }, 502);
  }
});
